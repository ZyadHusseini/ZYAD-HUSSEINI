/**
 * Regenerates the VideoObject JSON-LD in index.html from the esports clips in
 * src/data/content.ts.
 *
 * VideoObject is what makes a clip eligible for Google's video results and the
 * video thumbnail in normal results — without it these are just files the
 * crawler can see but cannot describe. Google requires name, description,
 * thumbnailUrl and uploadDate; contentUrl and duration are what let it actually
 * index and preview the file.
 *
 * Generated rather than hand-written for the same reason as the FAQ schema: a
 * second copy of the titles and durations maintained by hand drifts from the
 * component within a couple of edits.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const htmlPath = resolve(root, "index.html");
const ORIGIN = "https://www.zyadhusseini.com";

const { esports } = await import(resolve(root, "src/data/content.ts"));

/** Seconds -> ISO 8601 duration, e.g. 75 -> PT1M15S. */
const iso = (s) => {
  const m = Math.floor(s / 60);
  const r = s % 60;
  return `PT${m ? `${m}M` : ""}${r ? `${r}S` : m ? "" : "0S"}`;
};

const nodes = esports.clips.map((clip) => ({
  "@context": "https://schema.org",
  "@type": "VideoObject",
  name: clip.title,
  description: clip.description,
  thumbnailUrl: `${ORIGIN}${clip.poster}`,
  contentUrl: `${ORIGIN}${clip.src}`,
  // Publication date on this site, not the capture date.
  uploadDate: "2026-08-15",
  duration: iso(clip.seconds),
  width: clip.width,
  height: clip.height,
  isFamilyFriendly: true,
  inLanguage: "en",
  creator: { "@id": `${ORIGIN}/#zyad-husseini` },
  about: {
    "@type": "Thing",
    name: "Tekken esports",
    description: `${esports.game} competition on the ${esports.circuit} (${esports.league}).`,
  },
  keywords: [
    "Tekken",
    esports.game,
    "esports",
    esports.tag,
    "Tekken World Tour",
    esports.league,
    "Zyad Husseini",
  ].join(", "),
}));

const START = "<!-- VIDEO-SCHEMA:START (generated by scripts/sync-video-schema.mjs) -->";
const END = "<!-- VIDEO-SCHEMA:END -->";

const indent = (text, pad) =>
  text
    .split("\n")
    .map((l) => (l ? pad + l : l))
    .join("\n");

const scripts = nodes
  .map((n) =>
    ['    <script type="application/ld+json">', indent(JSON.stringify(n, null, 2), "      "), "    </script>"].join(
      "\n"
    )
  )
  .join("\n");

const block = [START, scripts, "    " + END].join("\n");

let html = readFileSync(htmlPath, "utf8");
const startIdx = html.indexOf(START);
if (startIdx === -1) {
  throw new Error(`Marker ${START} not found in index.html — add it (with ${END}) inside <head>.`);
}
const endIdx = html.indexOf(END, startIdx);
if (endIdx === -1) throw new Error(`Found ${START} but no matching ${END}.`);

html = html.slice(0, startIdx) + block.trimStart() + html.slice(endIdx + END.length);
writeFileSync(htmlPath, html);
console.log(`Video schema synced: ${nodes.length} VideoObject nodes written to index.html`);

/* ------------------------------------------------------------------ */
/* Video sitemap entries                                               */
/* ------------------------------------------------------------------ */

/**
 * The same clips also go into sitemap.xml under Google's video extension.
 * JSON-LD describes a video Google has already found; the sitemap is how it
 * finds one in the first place, and it is the documented submission path for
 * video indexing. Both are generated here so the titles, durations and
 * thumbnails cannot drift apart.
 *
 * Video entries are children of the page that embeds them, not their own
 * <url> — the clips are not standalone pages.
 */
const sitemapPath = resolve(root, "public/sitemap.xml");
const xmlEscape = (s) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

const videoEntries = esports.clips
  .map((clip) =>
    [
      "    <video:video>",
      `      <video:thumbnail_loc>${ORIGIN}${clip.poster}</video:thumbnail_loc>`,
      `      <video:title>${xmlEscape(clip.title)}</video:title>`,
      `      <video:description>${xmlEscape(clip.description)}</video:description>`,
      `      <video:content_loc>${ORIGIN}${clip.src}</video:content_loc>`,
      `      <video:duration>${clip.seconds}</video:duration>`,
      "      <video:publication_date>2026-08-15</video:publication_date>",
      "      <video:family_friendly>yes</video:family_friendly>",
      "      <video:live>no</video:live>",
      "    </video:video>",
    ].join("\n")
  )
  .join("\n");

const SM_START = "<!-- VIDEO-SITEMAP:START (generated by scripts/sync-video-schema.mjs) -->";
const SM_END = "<!-- VIDEO-SITEMAP:END -->";

let sitemap = readFileSync(sitemapPath, "utf8");
const smStart = sitemap.indexOf(SM_START);
if (smStart === -1) {
  throw new Error(`Marker ${SM_START} not found in sitemap.xml — add it (with ${SM_END}) inside the homepage <url>.`);
}
const smEnd = sitemap.indexOf(SM_END, smStart);
if (smEnd === -1) throw new Error(`Found ${SM_START} but no matching ${SM_END}.`);

const smBlock = [SM_START, videoEntries, "    " + SM_END].join("\n");
sitemap = sitemap.slice(0, smStart) + smBlock.trimStart() + sitemap.slice(smEnd + SM_END.length);
writeFileSync(sitemapPath, sitemap);
console.log(`Video sitemap synced: ${esports.clips.length} <video:video> entries written to sitemap.xml`);
