/**
 * Regenerates the VideoObject JSON-LD in index.html from the esports clips in
 * src/data/content.ts.
 *
 * VideoObject is what makes a clip eligible for Google's video results and the
 * video thumbnail in normal results — without it these are just files the
 * crawler can see but cannot describe. Google requires name, description,
 * thumbnailUrl and uploadDate; contentUrl and duration are what let it actually
 * index and preview the file.
 *
 * Generated rather than hand-written for the same reason as the FAQ schema: a
 * second copy of the titles and durations maintained by hand drifts from the
 * component within a couple of edits.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const htmlPath = resolve(root, "index.html");
const ORIGIN = "https://www.zyadhusseini.com";

const { esports } = await import(resolve(root, "src/data/content.ts"));

/** Seconds -> ISO 8601 duration, e.g. 75 -> PT1M15S. */
const iso = (s) => {
  const m = Math.floor(s / 60);
  const r = s % 60;
  return `PT${m ? `${m}M` : ""}${r ? `${r}S` : m ? "" : "0S"}`;
};

const nodes = esports.clips.map((clip) => ({
  "@context": "https://schema.org",
  "@type": "VideoObject",
  name: clip.title,
  description: clip.description,
  thumbnailUrl: `${ORIGIN}${clip.poster}`,
  contentUrl: `${ORIGIN}${clip.src}`,
  // Publication date on this site, not the capture date.
  uploadDate: "2026-08-15",
  duration: iso(clip.seconds),
  width: clip.width,
  height: clip.height,
  isFamilyFriendly: true,
  inLanguage: "en",
  creator: { "@id": `${ORIGIN}/#zyad-husseini` },
  about: {
    "@type": "Thing",
    name: "Tekken esports",
    description: `${esports.game} competition on the ${esports.circuit} (${esports.league}).`,
  },
  keywords: [
    "Tekken",
    esports.game,
    "esports",
    esports.tag,
    "Tekken World Tour",
    esports.league,
    "Zyad Husseini",
  ].join(", "),
}));

const START = "<!-- VIDEO-SCHEMA:START (generated by scripts/sync-video-schema.mjs) -->";
const END = "<!-- VIDEO-SCHEMA:END -->";

const indent = (text, pad) =>
  text
    .split("\n")
    .map((l) => (l ? pad + l : l))
    .join("\n");

const scripts = nodes
  .map((n) =>
    ['    <script type="application/ld+json">', indent(JSON.stringify(n, null, 2), "      "), "    </script>"].join(
      "\n"
    )
  )
  .join("\n");

const block = [START, scripts, "    " + END].join("\n");

let html = readFileSync(htmlPath, "utf8");
const startIdx = html.indexOf(START);
if (startIdx === -1) {
  throw new Error(`Marker ${START} not found in index.html — add it (with ${END}) inside <head>.`);
}
const endIdx = html.indexOf(END, startIdx);
if (endIdx === -1) throw new Error(`Found ${START} but no matching ${END}.`);

html = html.slice(0, startIdx) + block.trimStart() + html.slice(endIdx + END.length);
writeFileSync(htmlPath, html);
console.log(`Video schema synced: ${nodes.length} VideoObject nodes written to index.html`);
