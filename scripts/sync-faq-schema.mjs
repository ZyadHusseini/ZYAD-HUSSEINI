/**
 * Regenerates the FAQPage JSON-LD in index.html from src/data/content.ts.
 *
 * The FAQ answers need to exist as static HTML: the research behind this
 * section found that most AI-assistant crawlers do not execute JavaScript, so
 * a React-rendered JSON-LD block would be invisible to exactly the audience
 * the FAQ is written for. Hand-maintaining a second copy in index.html would
 * drift from the component within a couple of edits, so it is generated
 * instead and this script runs on every build.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const htmlPath = resolve(root, "index.html");

const { faqs } = await import(resolve(root, "src/data/content.ts"));

const node = {
  "@context": "https://schema.org",
  "@type": "FAQPage",
  "@id": "https://www.zyadhusseini.com/#faq",
  isPartOf: { "@id": "https://www.zyadhusseini.com/#website" },
  about: { "@id": "https://www.zyadhusseini.com/#zyad-husseini" },
  mainEntity: faqs.map((f) => ({
    "@type": "Question",
    name: f.question,
    acceptedAnswer: { "@type": "Answer", text: f.answer },
  })),
};

const START = "<!-- FAQ-SCHEMA:START (generated by scripts/sync-faq-schema.mjs) -->";
const END = "<!-- FAQ-SCHEMA:END -->";

const indent = (text, pad) =>
  text
    .split("\n")
    .map((l) => (l ? pad + l : l))
    .join("\n");

const block = [
  START,
  '    <script type="application/ld+json">',
  indent(JSON.stringify(node, null, 2), "      "),
  "    </script>",
  "    " + END,
].join("\n");

let html = readFileSync(htmlPath, "utf8");

const startIdx = html.indexOf(START);
if (startIdx === -1) {
  throw new Error(
    `Marker ${START} not found in index.html — add it (with ${END}) inside <head> before running this script.`
  );
}
const endIdx = html.indexOf(END, startIdx);
if (endIdx === -1) throw new Error(`Found ${START} but no matching ${END} in index.html.`);

const before = html.slice(0, startIdx);
const after = html.slice(endIdx + END.length);
html = before + block.trimStart() + after;

writeFileSync(htmlPath, html);
console.log(`FAQ schema synced: ${faqs.length} questions written to index.html`);
